#!/usr/bin/env bash
# usage: tools/goldens.sh check [BIN]   -- run every row of goldens/matrix.tsv, compare the output-tree hash with goldens/hashes.tsv
#        tools/goldens.sh write [BIN]   -- regenerate goldens/hashes.tsv (do this ONLY after bench/oracle.php agreed with PHP CS Fixer)
# A row = a corpus directory + a rules spec. The corpus is COPIED, `fix`ed (--no-cache --allow-risky=yes, cwd outside the repo so
# no config is picked up) and the tree is hashed: sha256 of the sorted `sha256  path` listing of its *.php files.
# No php needed. The binary runs through bench/gfmt.sh (2 GB RSS / 60 s watchdog).
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"; cd "$ROOT"
G="${GOLDENS_DIR:-$ROOT/goldens}"; CR="${CORPUS_ROOT:-$ROOT}"   # tools/corpora.sh points these at a corpora asset
mode="${1:?usage: tools/goldens.sh check|write [BIN]}"
export REAL_BIN="${2:-$ROOT/bin/manticore-fmt}"
export GFMT_LOG="${GFMT_LOG:-${TMPDIR:-/tmp}/gfmt-blowups.log}"
if command -v sha256sum >/dev/null 2>&1; then sum() { sha256sum; }; else sum() { shasum -a 256; }; fi
tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT

treehash() { # <dir>
  (cd "$1" && find . -type f -name '*.php' | LC_ALL=C sort | while IFS= read -r f; do printf '%s  %s\n' "$(sum < "$f" | cut -d' ' -f1)" "$f"; done | sum | cut -d' ' -f1)
}

out="$tmp/hashes.tsv"; : > "$out"
while IFS=$'\t' read -r corpus id kind rules; do
  case "$corpus" in ''|'#'*) continue;; esac
  w="$tmp/w"; rm -rf "$w"; mkdir -p "$w"; cp -R "$CR/$corpus/." "$w/"
  (cd "$tmp" && "$ROOT/bench/gfmt.sh" fix --no-cache --allow-risky=yes --rules="$rules" "$w" >/dev/null 2>&1) || rc=$?
  rc="${rc:-0}"; unset rc
  printf '%s\t%s\t%s\t%s\n' "$corpus" "$id" "$(treehash "$w")" "$kind" >> "$out"
done < "$G/matrix.tsv"

if [ "$mode" = write ]; then
  { printf '# corpus\tid\tsha256 of the output tree\tkind (see matrix.tsv); generated by tools/goldens.sh write\n'; cat "$out"; } > "$G/hashes.tsv"
  echo "goldens: wrote $(wc -l < "$out" | tr -d ' ') rows"; exit 0
fi
bad=0
while IFS=$'\t' read -r corpus id got kind; do
  want="$(awk -F'\t' -v c="$corpus" -v i="$id" '$1==c && $2==i {print $3}' "$G/hashes.tsv")"
  if [ "$want" != "$got" ]; then echo "MISMATCH [$kind] $corpus $id: want ${want:-<none>} got $got"; bad=1; fi
done < "$out"
[ $bad = 0 ] && echo "goldens: all $(wc -l < "$out" | tr -d ' ') rows match" || exit 1
