<?php

declare(strict_types=1);

// usage: php -d xdebug.mode=off bench/gen_tables.php
// Dev helper (Zend): dumps upstream's built-in rule sets and fixer metadata into src/RuleSetTable.php and
// src/FixerTable.php (JSON in a nowdoc each). The binary never parses upstream at run time; regenerate on an upstream bump.

require __DIR__.'/lib.php';
require FORK.'/bench/work/upstream/vendor/autoload.php';

use PhpCsFixer\Fixer\ConfigurableFixerInterface;
use PhpCsFixer\Fixer\DeprecatedFixerInterface;
use PhpCsFixer\FixerFactory;
use PhpCsFixer\RuleSet\DeprecatedRuleSetDefinitionInterface;
use PhpCsFixer\RuleSet\RuleSets;

error_reporting(E_ALL & ~E_DEPRECATED);

$ver = PhpCsFixer\Console\Application::VERSION;
$sets = [];
foreach (RuleSets::getSetDefinitions() as $name => $def) {
    $sets[$name] = [
        'rules' => $def instanceof PhpCsFixer\RuleSet\AutomaticRuleSetDefinitionInterface ? [] : $def->getRules(),
        'risky' => $def->isRisky(),
        'auto' => $def instanceof PhpCsFixer\RuleSet\AutomaticRuleSetDefinitionInterface,
        'desc' => $def->getDescription(),
        'succ' => $def instanceof DeprecatedRuleSetDefinitionInterface ? $def->getSuccessorsNames() : null,
    ];
}

function jsonSafe(mixed $v): mixed
{
    if (is_array($v)) {
        return array_map('jsonSafe', $v);
    }
    if (is_scalar($v) || null === $v) {
        return $v;
    }

    return '<'.get_debug_type($v).'>';
}

$fixers = [];
$factory = (new FixerFactory())->registerBuiltInFixers();
foreach ($factory->getFixers() as $f) {
    $e = [
        'risky' => $f->isRisky(),
        'prio' => $f->getPriority(),
        'succ' => $f instanceof DeprecatedFixerInterface ? $f->getSuccessorsNames() : null,
        'sum' => $f->getDefinition()->getSummary(),
        'opts' => [],
    ];
    if ($f instanceof ConfigurableFixerInterface) {
        foreach ($f->getConfigurationDefinition()->getOptions() as $o) {
            $a = $o->getAllowedValues();
            $e['opts'][] = [
                'name' => $o->getName(),
                'desc' => $o->getDescription(),
                'types' => $o->getAllowedTypes(),
                'allowed' => null === $a ? null : array_values(array_filter(array_map('jsonSafe', $a), static fn ($x) => !is_string($x) || !str_starts_with($x, '<'))),
                'def' => $o->hasDefault() ? jsonSafe($o->getDefault()) : null,
            ];
        }
    }
    $fixers[$f->getName()] = $e;
}
ksort($fixers);

function emit(string $file, string $class, string $doc, array $data, string $ver): void
{
    $json = json_encode($data, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_PRESERVE_ZERO_FRACTION | JSON_THROW_ON_ERROR);
    if (str_contains($json, "\nJSON")) {
        throw new RuntimeException('nowdoc terminator in data');
    }
    file_put_contents($file, "<?php\n\ndeclare(strict_types=1);\n\nnamespace Fmt;\n\n/**\n * GENERATED by bench/gen_tables.php from php-cs-fixer $ver: do not edit.\n * $doc\n */\nfinal class $class\n{\n    public const JSON = <<<'JSON'\n$json\nJSON;\n}\n");
}
emit(__DIR__.'/../src/RuleSetTable.php', 'RuleSetTable', 'name => {rules (raw, nested @sets kept), risky, auto, desc, succ}', $sets, $ver);
emit(__DIR__.'/../src/FixerTable.php', 'FixerTable', 'name => {risky, prio, succ (deprecated fixer: successors), sum, opts: [{name, desc, types, allowed, def}]}', $fixers, $ver);
echo count($sets).' sets, '.count($fixers)." fixers\n";
