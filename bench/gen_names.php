<?php

declare(strict_types=1);

// usage: php -d xdebug.mode=off bench/gen_names.php
// Dev helper (Zend): dumps the internal function and class names of THIS php into src/NativeNames.php. native_function_casing and
// class_reference_name_casing ask upstream's runtime (get_defined_functions / get_declared_classes + isInternal); the native binary has no
// php, so it carries the list of the php that built it (the oracle's). Regenerate on a php / extension change.

$fn = get_defined_functions()['internal'];
sort($fn);
$cl = [];
foreach (get_declared_classes() as $c) {
    if ((new ReflectionClass($c))->isInternal()) {
        $cl[] = $c;
    }
}
sort($cl);
$out = "<?php\n\ndeclare(strict_types=1);\n\nnamespace Fmt;\n\n/** GENERATED by bench/gen_names.php (php ".PHP_VERSION."): internal function / class names, one per line, canonical case. */\nfinal class NativeNames\n{\n";
$out .= '    public const FUNCTIONS = '.var_export(implode("\n", $fn), true).";\n\n";
$out .= '    public const CLASSES = '.var_export(implode("\n", $cl), true).";\n}\n";
file_put_contents(__DIR__.'/../src/NativeNames.php', $out);
echo count($fn).' functions, '.count($cl)." classes\n";
