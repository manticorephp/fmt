<?php

declare(strict_types=1);

// usage: php -d xdebug.mode=off bench/gen_names.php
// Dev helper (Zend): dumps the internal function, class and constant names of THIS php into src/NativeNames.php. native_function_casing and
// class_reference_name_casing ask upstream's runtime (get_defined_functions / get_declared_classes + isInternal); the native binary has no
// php, so it carries the list of the php that built it (the oracle's). Regenerate on a php / extension change.

$fn = get_defined_functions()['internal'];
sort($fn);
$cl = [];
foreach (get_declared_classes() as $c) {
    if ((new ReflectionClass($c))->isInternal()) {
        $cl[] = $c;
    }
}
sort($cl);
$k = get_defined_constants(true);
unset($k['user']);
$co = [];
foreach ($k as $group) {
    foreach ($group as $name => $_) {
        $co[$name] = true;
    }
}
$co = array_keys($co);
sort($co);
// class_keyword asks class_exists / interface_exists / trait_exists in upstream's process: the internal ones + whatever upstream's composer autoloader can load
$like = [];
foreach (array_merge(get_declared_classes(), get_declared_interfaces(), get_declared_traits()) as $c) {
    if ((new ReflectionClass($c))->isInternal()) {
        $like[(new ReflectionClass($c))->getName()] = true;
    }
}
$up = '/Users/taras/var/projects/php-cs-fixer-ds/bench/work/upstream';
if (is_file($up.'/vendor/autoload.php')) {
    require $up.'/vendor/autoload.php';
    $cands = array_keys(require $up.'/vendor/composer/autoload_classmap.php');
    foreach (require $up.'/vendor/composer/autoload_psr4.php' as $prefix => $dirs) {
        foreach ($dirs as $dir) {
            if (!is_dir($dir)) {
                continue;
            }
            foreach (new RecursiveIteratorIterator(new RecursiveDirectoryIterator($dir, FilesystemIterator::SKIP_DOTS)) as $fi) {
                if ('php' === $fi->getExtension() && !str_contains($fi->getPathname(), '/Resources/') && ctype_upper($fi->getFilename()[0])) {
                    $cands[] = $prefix.str_replace('/', '\\', substr($fi->getPathname(), strlen($dir) + 1, -4));
                }
            }
        }
    }
    foreach (array_unique($cands) as $c) {
        try {
            $ok = class_exists($c) || interface_exists($c) || trait_exists($c);
        } catch (Throwable) {
            $ok = false;
        }
        if ($ok) {
            $like[(new ReflectionClass($c))->getName()] = true;
        }
    }
}
$like = array_keys($like);
sort($like);
$out = "<?php\n\ndeclare(strict_types=1);\n\nnamespace Fmt;\n\n/** GENERATED by bench/gen_names.php (php ".PHP_VERSION."): internal function / class / constant names (get_defined_constants minus `user`), one per line, canonical case. */\nfinal class NativeNames\n{\n";
$out .= '    public const FUNCTIONS = '.var_export(implode("\n", $fn), true).";\n\n";
$out .= '    public const CLASSES = '.var_export(implode("\n", $cl), true).";\n\n";
$out .= "    public const CLASS_LIKE = ".var_export(implode("\n", $like), true).";\n\n";
$out .= '    public const CONSTANTS = '.var_export(implode("\n", $co), true).";\n}\n";
file_put_contents(__DIR__.'/../src/NativeNames.php', $out);
echo count($fn).' functions, '.count($cl).' classes, '.count($co)." constants\n";
