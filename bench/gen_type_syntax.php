<?php

declare(strict_types=1);

// usage: php -d xdebug.mode=off bench/gen_type_syntax.php
// Dev helper (Zend): writes src/TypeSyntax.php. The phpdoc_to_{param,property,return}_type rules ask upstream whether `<?php function f(%s $x) {}` (and the property / return
// templates) parses (Tokens::fromCode). The types they ask about are names joined by `|`, so the answer depends on the reserved words only: every reserved word is run through the
// real tokenizer alone, as a union member and as an intersection member in each template; every other name is always valid.

$up = getenv('UPSTREAM_DIR') ?: __DIR__.'/work/upstream';
require $up.'/vendor/autoload.php';

use PhpCsFixer\Tokenizer\Tokens;

$words = [];
// reserved words, magic constants and the contextual ones
foreach (explode(' ', 'abstract and array as break callable case catch class clone const continue declare default die do echo else elseif empty enddeclare endfor endforeach endif endswitch endwhile enum eval exit extends final finally fn for foreach function global goto if implements include include_once instanceof insteadof interface isset list match namespace new or print private protected public readonly require require_once return static switch throw trait try unset use var while xor yield from __halt_compiler __class__ __dir__ __file__ __function__ __line__ __method__ __namespace__ __trait__ __property__ self parent null true false int float string bool iterable object mixed never void resource numeric scalar set get') as $w) {
    $words[$w] = true;
}
// completeness: every other word that does not lex as a T_STRING in the sample is a reserved word the list above missed
$sample = array_merge(explode("\n", file_get_contents($up.'/../../../../manticore-fmt/src/NativeNames.php')), []);
foreach (get_defined_functions()['internal'] as $f) {
    $sample[] = $f;
}
foreach ($sample as $w) {
    $w = strtolower(trim($w, " \t';\\"));
    if (preg_match('/^[a-z_][a-z0-9_]*$/', $w) && !isset($words[$w])) {
        $tok = @token_get_all('<?php '.$w.' ');
        if (isset($tok[1]) && is_array($tok[1]) && T_STRING !== $tok[1][0]) {
            fwrite(STDERR, "reserved word missing from the list: $w\n");
            $words[$w] = true;
        }
    }
}
ksort($words);

$tpl = ['param' => '<?php function f(%s $x) {}', 'property' => '<?php class A { private %s $b; }', 'return' => '<?php function f(): %s {}'];
/** 'ok' | 'parse' (ParseError) | 'fatal' (a compile error raised by the parser itself, which kills the whole upstream process) */
function probe(string $code): string
{
    static $cache = [];
    if (isset($cache[$code])) {
        return $cache[$code];
    }
    $out = [];
    exec('php -n -d display_errors=0 -r '.escapeshellarg('try { token_get_all($argv[1], TOKEN_PARSE); echo "ok"; } catch (ParseError) { echo "parse"; }').' '.escapeshellarg($code).' 2>/dev/null', $out, $rc);

    return $cache[$code] = (($out[0] ?? '') === 'ok' || ($out[0] ?? '') === 'parse') ? $out[0] : 'fatal';
}

function ok(string $code): bool
{
    return 'ok' === probe($code);
}

$alone = [];
$fatal = [];
$union = [];
$inter = [];
foreach ($tpl as $name => $t) {
    foreach (array_keys($words) as $w) {
        foreach ([$w, strtoupper($w), ucfirst($w)] as $form) {
            if (ok(sprintf($t, $form)) !== ok(sprintf($t, $w))) {
                fwrite(STDERR, "case differs: $form\n");
            }
        }
        if (ok(sprintf($t, $w))) {
            $alone[$name][] = $w;
        }
        foreach (['alone' => [$w], 'union' => [$w.'|int', 'int|'.$w, 'int|'.$w.'|int'], 'inter' => [$w.'&int', 'int&'.$w, 'int&'.$w.'&int']] as $form => $codes) {
            foreach ($codes as $c) {
                if ('fatal' === probe(sprintf($t, $c))) {
                    $fatal[$form][$name][$w] = true;
                }
            }
        }
        if (ok(sprintf($t, $w.'|int')) && ok(sprintf($t, 'int|'.$w)) && ok(sprintf($t, 'int|'.$w.'|int'))) {
            $union[$name][] = $w;
        } elseif (ok(sprintf($t, $w.'|int')) || ok(sprintf($t, 'int|'.$w))) {
            fwrite(STDERR, "position-dependent union member: $name $w\n");
        }
        if (ok(sprintf($t, $w.'&int')) && ok(sprintf($t, 'int&'.$w)) && ok(sprintf($t, 'int&'.$w.'&int'))) {
            $inter[$name][] = $w;
        } elseif (ok(sprintf($t, $w.'&int')) || ok(sprintf($t, 'int&'.$w))) {
            fwrite(STDERR, "position-dependent intersection member: $name $w\n");
        }
    }
}
$all = implode(' ', array_keys($words));
$out = "<?php\n\ndeclare(strict_types=1);\n\nnamespace Fmt;\n\n/** GENERATED by bench/gen_type_syntax.php: which reserved words parse as a (sole / union member / intersection member) type in the templates of phpdoc_to_param_type, phpdoc_to_property_type and phpdoc_to_return_type. */\nfinal class TypeSyntax\n{\n";
$out .= '    public const RESERVED = '.var_export($all, true).";\n\n";
foreach (['FATAL_ALONE' => array_map(static fn (array $a) => array_keys($a), $fatal['alone'] ?? []), 'FATAL_UNION' => array_map(static fn (array $a) => array_keys($a), $fatal['union'] ?? []), 'FATAL_INTER' => array_map(static fn (array $a) => array_keys($a), $fatal['inter'] ?? []), 'ALONE' => $alone, 'UNION' => $union, 'INTER' => $inter] as $const => $data) {
    foreach ($tpl as $name => $_) {
        $out .= '    public const '.$const.'_'.strtoupper($name).' = '.var_export(implode(' ', $data[$name] ?? []), true).";\n";
    }
    $out .= "\n";
}
$out = rtrim($out)."\n}\n";
file_put_contents(__DIR__.'/../src/TypeSyntax.php', $out);
foreach (['alone' => $alone, 'union' => $union, 'inter' => $inter] as $k => $d) {
    foreach ($d as $n => $l) {
        echo "$k $n: ".implode(' ', $l)."\n";
    }
}
